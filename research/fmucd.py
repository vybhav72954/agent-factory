MIN_CHARS, MAX_CHARS = 3, 200


def _chunks(chunksize: int = 500_000):
    return pd.read_csv(CSV_PATH, usecols=COLS, dtype=str, chunksize=chunksize, on_bad_lines="skip")


def unplanned() -> pd.DataFrame:
    """Unplanned work orders with a usable description (no model involved)."""
    keep = []
    for chunk in _chunks():
        c = chunk[chunk["PPM/UPM"].str.upper().fillna("") == "UPM"].copy()
        # Excel export artefacts: "_x000D_" carriage returns and collapsed whitespace. Cleaning is
        # identical for every strategy and does not touch wording.
        c["WODescription"] = (c["WODescription"].fillna("").str.replace("_x000D_", " ", regex=False)
                              .str.replace(r"\s+", " ", regex=True).str.strip())
        c = c[c["WODescription"].str.len().between(MIN_CHARS, MAX_CHARS)]
        keep.append(c)
    df = pd.concat(keep, ignore_index=True)
    df["WOPriority"] = df["WOPriority"].fillna("").str.strip()
    return df[df["WOPriority"] != ""]


