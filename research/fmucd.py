"""
research/fmucd.py

External check on real maintenance work orders (analysis plan: research/AEI/analysis_plan_additions.md, section G).

Data: Facility Management Unified Classification Database (FMUCD), Mendeley Data
doi:10.17632/cb8d2nsjss.1 — 3,693,867 work orders from 12 North American universities with a
free-text `WODescription` and the organisation's own `WOPriority` code. The CSV (1.4 GB) is
downloaded to research/external/fmucd/fmucd.csv (gitignored, not redistributed).

Three steps, in order:

    inspect   priority-code profile per university, from label metadata only (no model runs),
              written to research/results/fmucd/priority_profile.md. Used to write the mapping
              from each university's codes to LOW / MEDIUM / HIGH by hand into
              research/external/fmucd_mapping.json, which is frozen before sampling.
    sample    unplanned work orders whose description is 3-200 characters and passes the
              production input guard, de-duplicated, seeded stratified sample across the three
              mapped bands and the universities -> research/results/fmucd/sample.csv.
    oracle    upper bound: classifiers trained on FMUCD's own labels (work orders disjoint from the
              sample) and tested on the sample, to show how much of the priority band is predictable
              from the text at all. Added after the agreement step came out near chance.
    score     agreement of every strategy with the mapped band: 3-class accuracy, quadratic
              weighted kappa, confusion, cluster bootstrap CIs and paired sign-flip tests.
              LLM outputs come from `collect.py --bank fmucd`; the non-LLM arms are computed here.

The recorded priority is scheduling policy as much as severity, so this is an agreement study,
not an accuracy test, and is reported as such.

Usage:
    python -m research.fmucd inspect
    python -m research.fmucd sample
    python -m research.fmucd score

Output:
    research/results/fmucd/{priority_profile.md,sample.csv,agreement.csv,summary.md}
"""

