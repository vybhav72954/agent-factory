def inspect() -> Path:
    df = unplanned()
    rng = np.random.default_rng(SEED)
    md = ["# FMUCD priority-code profile (unplanned work orders)\n",
          "**Generated by:** `python -m research.fmucd inspect`\n",
          "Label metadata only: no strategy has been run on this data. Used to write "
          "`research/external/fmucd_mapping.json` (analysis plan section G, stage 1).\n",
          f"Unplanned work orders with a 3–200 character description: {len(df):,} "
          f"across {df['UniversityID'].nunique()} universities.\n"]
    for uni, g in df.groupby("UniversityID"):
        counts = g["WOPriority"].value_counts()
        md.append(f"\n## University {uni} — {len(g):,} work orders, {len(counts)} priority codes\n")
        md.append("| Priority | Work orders | Share | Example descriptions |")
        md.append("|---|---|---|---|")
        for code, n in counts.head(12).items():
            sub = g[g["WOPriority"] == code]["WODescription"]
            picks = sub.iloc[rng.choice(len(sub), size=min(3, len(sub)), replace=False)].tolist()
            md.append(f"| {code} | {n:,} | {n / len(g):.1%} | " + "; ".join(p.replace("|", "/")[:70] for p in picks) + " |")
        if len(counts) > 12:
            md.append(f"| … {len(counts) - 12} more codes | {counts.iloc[12:].sum():,} | | |")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "priority_profile.md"
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
    return path


