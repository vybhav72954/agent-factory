def sample() -> Path:
    from agents.input_guard import is_valid_fault_input

    mapping = json.loads(MAPPING_PATH.read_text(encoding="utf-8"))
    codes = {(u, c): band for u, spec in mapping["universities"].items()
             for band, cs in spec["bands"].items() for c in cs}
    df = unplanned()
    df["band"] = [codes.get((u, c)) for u, c in zip(df["UniversityID"], df["WOPriority"])]
    mapped = df[df["band"].notna()].copy()
    mapped["guard_ok"] = [is_valid_fault_input(t)[0] for t in mapped["WODescription"]]
    guard_rate = float(mapped["guard_ok"].mean())
    pool = mapped[mapped["guard_ok"]].drop_duplicates(subset=["WODescription"])

    rng = np.random.default_rng(SEED)
    picks = []
    for band, g in pool.groupby("band"):
        # spread across universities: round-robin over universities, seeded order within each
        per_uni = {u: sub.iloc[rng.permutation(len(sub))] for u, sub in g.groupby("UniversityID")}
        order, i = [], 0
        while len(order) < min(SAMPLE_PER_BAND, len(g)):
            added = False
            for u, sub in per_uni.items():
                if i < len(sub) and len(order) < min(SAMPLE_PER_BAND, len(g)):
                    order.append(sub.iloc[i])
                    added = True
            if not added:
                break
            i += 1
        picks.append(pd.DataFrame(order))
    out = pd.concat(picks, ignore_index=True)
    out = out.rename(columns={"WOID": "bank_id", "WODescription": "text", "UniversityID": "university"})
    out["design_severity"] = out["band"]
    out["style"] = "workorder"
    out["anchor"] = out["university"]
    out = out[["bank_id", "text", "design_severity", "style", "anchor", "university", "WOPriority",
               "SystemDescription", "ComponentDescription"]]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out.to_csv(SAMPLE_PATH, index=False)
    meta = {"unplanned_with_description": int(len(df)), "mapped": int(len(mapped)),
            "input_guard_pass_rate": guard_rate, "pool_after_dedup": int(len(pool)),
            "sampled": int(len(out)), "by_band": out["design_severity"].value_counts().to_dict(),
            "by_university": out["university"].value_counts().to_dict(), "seed": SEED}
    (OUT_DIR / "sample_meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return SAMPLE_PATH


def load_sample(fewshot: bool = False) -> list[dict]:
    """Prompt-bank interface for collect.py. With fewshot=True each prompt carries a system prompt
    that appends labelled examples from its own university (analysis plan section H)."""
    df = pd.read_csv(SAMPLE_PATH)
    prompts = [{"id": r.bank_id, "text": r.text, "design_severity": r.design_severity, "style": r.style,
                "anchor": r.anchor, "machine_id": 1} for r in df.itertuples()]
    if fewshot:
        blocks = fewshot_prompts()
        for prompt, uni in zip(prompts, df["university"].astype(str)):
            prompt["system_prompt"] = blocks[uni]
    return prompts


def build_fewshot_examples() -> Path:
    """20 labelled work orders per university, drawn from the mapped pool outside the sample."""
    mapping = json.loads(MAPPING_PATH.read_text(encoding="utf-8"))
    codes = {(u, c): band for u, spec in mapping["universities"].items()
             for band, cs in spec["bands"].items() for c in cs}
    sample_df = pd.read_csv(SAMPLE_PATH)
    df = unplanned()
    df["band"] = [codes.get((u, c)) for u, c in zip(df["UniversityID"], df["WOPriority"])]
    pool = df[df["band"].notna() & ~df["WODescription"].isin(set(sample_df["text"]))]
    pool = pool.drop_duplicates(subset=["WODescription"])
    rng = np.random.default_rng(SEED)
    out = {}
    for uni, g in pool.groupby("UniversityID"):
        bands = list(g["band"].unique())
        per_band = max(1, FEWSHOT_PER_SITE // len(bands))
        picks = []
        for band, sub in g.groupby("band"):
            take = sub.iloc[rng.permutation(len(sub))[:per_band]]
            picks += [{"text": r.WODescription, "band": band} for r in take.itertuples()]
        rng.shuffle(picks)
        out[str(uni)] = picks[:FEWSHOT_PER_SITE]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    FEWSHOT_PATH.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print({u: len(v) for u, v in out.items()})
    return FEWSHOT_PATH


def fewshot_prompts() -> dict[str, str]:
    """University id -> production system prompt with that site's labelled examples appended."""
    from agents.prompts import DIAGNOSTIC_SYSTEM_PROMPT

    examples = json.loads(FEWSHOT_PATH.read_text(encoding="utf-8"))
    blocks = {}
    header = ("\n== SEVERITY EXAMPLES FROM THIS SITE (FOLLOW THESE CONVENTIONS) ==\n"
              "Past work orders from the same maintenance organisation, with the severity that "
              "organisation assigned. Use them to calibrate fault_severity for this site.\n")
    for uni, rows in examples.items():
        lines = "\n".join('  "{}" -> {}'.format(r["text"], r["band"]) for r in rows)
        blocks[uni] = DIAGNOSTIC_SYSTEM_PROMPT + header + lines + "\n"
    return blocks


def check_sample(fewshot: bool = False) -> list[str]:
    if not SAMPLE_PATH.exists():
        return ["sample.csv missing: run `python -m research.fmucd sample` first"]
    df = pd.read_csv(SAMPLE_PATH)
    problems = []
    if df["bank_id"].duplicated().any():
        problems.append("duplicate work-order ids")
    if not set(df["design_severity"]) <= set(LABELS):
        problems.append("unexpected band label")
    if fewshot and not FEWSHOT_PATH.exists():
        problems.append("fewshot_examples.json missing: run `python -m research.fmucd fewshot` first")
    return problems


